-- =====================================================================
-- country_league_master に「リーグレベル」league_level を追加する  ※ soccer_bm_master
--
--   league_level … 同じ国の中でのリーグの格。1 = 最上位、数字が大きいほど下位（1, 2, 3 ...）
--                  例: イングランド  プレミアリーグ = 1 / EFL チャンピオンシップ = 2 / EFL リーグ 1 = 3
--                  NULL = 未設定（後で管理画面から設定する）。昇格・降格はこの値の比較で表す。
--                  1 行 = チームなので、同じ 国・リーグ の行はすべて同じ値にする（管理画面は 国・リーグ 単位で更新する想定）。
--
--   列の順番: フラグ類と同じく register_id の前（del_flg の後）に置くため、ALTER TABLE ADD COLUMN ではなく作り直す。
--     ① country_league_master_bk に退避（データのコピー）
--     ② country_league_master を作り直す（id はそのまま引き継ぎ、IDENTITY の採番も続きから）
--     ③ 退避したデータを戻す（league_level は NULL）
--     ④ 確認。問題なければ後日 DROP TABLE country_league_master_bk;
--
--   流し方: ⓪ の結果（今の索引・制約・参照）を確認してから、そのまま最後まで流す（1 トランザクション。途中で失敗したら何も変わらない）。
--           ⓪ で下の ② に無い索引・制約が出たら、② の最後に同じものを足してから流すこと。
-- =====================================================================

-- ⓪ 事前確認（流す前に見るだけ）
--   今の列
SELECT ordinal_position, column_name, data_type, is_nullable, column_default, is_identity
  FROM information_schema.columns
 WHERE table_schema = current_schema() AND table_name = 'country_league_master'
 ORDER BY ordinal_position;
--   今の索引・制約（② で作り直すものと比べる）
SELECT indexname, indexdef FROM pg_indexes
 WHERE schemaname = current_schema() AND tablename = 'country_league_master';
SELECT conname, pg_get_constraintdef(oid) FROM pg_constraint
 WHERE conrelid = 'country_league_master'::regclass;
--   このテーブルを参照している VIEW・外部キー（あれば DROP できないので先に相談）
SELECT DISTINCT v.relname AS dependent_view
  FROM pg_depend d
  JOIN pg_rewrite r ON r.oid = d.objid
  JOIN pg_class v   ON v.oid = r.ev_class
 WHERE d.refobjid = 'country_league_master'::regclass AND v.relname <> 'country_league_master';
SELECT conname, conrelid::regclass FROM pg_constraint
 WHERE confrelid = 'country_league_master'::regclass;
--   件数
SELECT COUNT(*) AS rows, MAX(id) AS max_id FROM country_league_master;


-- ①〜③ 作り直し
BEGIN;

DO $$
BEGIN
  IF to_regclass('country_league_master_bk') IS NOT NULL THEN
    RAISE EXCEPTION 'country_league_master_bk が既にあります（前回の残り）。中身を確認して消してから流してください';
  END IF;
END
$$;

-- ① 退避（データだけのコピー。索引・制約は付かない）
CREATE TABLE country_league_master_bk AS TABLE country_league_master;

-- ② 作り直し（参照している VIEW・外部キーがあればここで失敗して全部戻る）
DROP TABLE country_league_master;

CREATE TABLE country_league_master (
  id            INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  country       VARCHAR(255)  NOT NULL,
  league        VARCHAR(255)  NOT NULL,
  sub_league    VARCHAR(255),
  team          VARCHAR(255)  NOT NULL,
  link          VARCHAR(2048) NOT NULL,
  del_flg       CHAR(1),
  league_level  SMALLINT,                                  -- リーグレベル（同じ国で 1 = 最上位、大きいほど下位。NULL = 未設定）
  register_id   VARCHAR(100)  NOT NULL,
  register_time TIMESTAMP WITH TIME ZONE NOT NULL,
  update_id     VARCHAR(100)  NOT NULL,
  update_time   TIMESTAMP WITH TIME ZONE NOT NULL,
  CONSTRAINT ck_country_league_master_league_level CHECK (league_level IS NULL OR league_level >= 1)
);

COMMENT ON COLUMN country_league_master.league_level IS
  'リーグレベル。同じ国の中で 1 = 最上位、数字が大きいほど下位。NULL = 未設定。同じ国・リーグの行は同じ値にする';

-- 国・リーグで引く（管理画面のリーグ一覧・レベル更新、昇格・降格の判定用）
CREATE INDEX idx_country_league_master_country_league ON country_league_master (country, league);

-- ③ 戻す（id はそのまま）
INSERT INTO country_league_master
  (id, country, league, sub_league, team, link, del_flg, league_level,
   register_id, register_time, update_id, update_time)
OVERRIDING SYSTEM VALUE
SELECT id, country, league, sub_league, team, link, del_flg, NULL,
       register_id, register_time, update_id, update_time
  FROM country_league_master_bk;

-- IDENTITY の採番を続きから（次の id = 今の最大 + 1）
SELECT setval(pg_get_serial_sequence('country_league_master', 'id'),
              COALESCE((SELECT MAX(id) FROM country_league_master), 0) + 1, false);

-- ④ 確認（件数が違えば全部戻す）
DO $$
DECLARE
  v_bk  bigint;
  v_new bigint;
BEGIN
  SELECT COUNT(*) INTO v_bk  FROM country_league_master_bk;
  SELECT COUNT(*) INTO v_new FROM country_league_master;
  IF v_bk <> v_new THEN
    RAISE EXCEPTION '件数が合いません（退避 % 件 / 戻し % 件）', v_bk, v_new;
  END IF;
  RAISE NOTICE '戻した行: % 件', v_new;
END
$$;

COMMIT;

-- ⑤ 流した後の確認
--   列の順番（league_level が del_flg と register_id の間にあること）
SELECT ordinal_position, column_name, data_type FROM information_schema.columns
 WHERE table_schema = current_schema() AND table_name = 'country_league_master'
 ORDER BY ordinal_position;
--   中身が退避前と同じこと（0 件なら一致）
SELECT id, country, league, sub_league, team, link, del_flg, register_id, register_time, update_id, update_time
  FROM country_league_master_bk
EXCEPT
SELECT id, country, league, sub_league, team, link, del_flg, register_id, register_time, update_id, update_time
  FROM country_league_master;
